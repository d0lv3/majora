/**
 * Only a handful of majors are written up so far. The rest ship as "coming
 * soon" cards: still listed, still searchable, but not yet openable — the
 * shelf should show its full shape even while it is being filled.
 *
 * A major is live when it carries `available: true`; anything missing the
 * flag is treated as not ready.
 */
export const isAvailable = (major) => major?.available === true

export const availableMajors = () => MAJORS.filter(isAvailable)

export const fieldLabel = (id) => FIELDS.find((f) => f.id === id)?.label ?? id

export const getMajor = (slug) => MAJORS.find((m) => m.slug === slug)

export const countByField = () =>
  FIELDS.map((field) => ({
    ...field,
    count: MAJORS.filter((m) => m.field === field.id).length,
  }))
